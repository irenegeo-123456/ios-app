#!/usr/bin/env node
// Copies what the clone needs out of Slack's iOS app and its design tokens, into committed files:
//
//   colors  slack/design-tokens output/ios/Colors.swift → src/tokens/generated/colors.{css,ts}
//   icons   Modules/Data/Icon/ResourceBundle/Icons.xcassets/*.svg → src/icons/generated/icons.json
//   fonts   Modules/Data/Font/ResourceBundle/Font/Lato/*.ttf → public/fonts/*.woff (lossless)
//   sounds  App/Resource/Sounds/*.mp3 → public/sounds/
//
//   npm run harvest                 everything
//   npm run harvest -- colors icons one or more parts
//
// Sources are found through tools/ios/paths.mjs (SLACK_IOS_DIR, SLACK_DESIGN_TOKENS_DIR). Re-run it when the iOS
// checkout or the pinned design-tokens commit changes, and commit what it writes.

import fs from 'node:fs'
import path from 'node:path'
import { DESIGN_TOKENS_DIR, DESIGN_TOKENS_SHA, IOS_DIR, ROOT, VENDOR_DIR, need } from './paths.mjs'
import { ttfToWoff } from '../lib/woff.mjs'

const parts = process.argv.slice(2)
const want = (p) => parts.length === 0 || parts.includes(p)
const rel = (p) => path.relative(ROOT, p)
const write = (file, data) => {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, data)
  console.log(`  wrote ${rel(file)} (${(Buffer.byteLength(data) / 1024).toFixed(1)} KB)`)
}

// ------------------------------------------------------------------------------------------------ colors

function hex8(v) {
  const s = v.toLowerCase().replace(/^0x/, '').padStart(8, '0')
  return s.endsWith('ff') ? `#${s.slice(0, 6)}` : `#${s}`
}

/**
 * Parses Colors.swift: `static let dt_… = UIColor(hex8: 0x…)` or `UIColor(light: …, dark: …[, trueDark: …,
 * elevatedDark: …][, lightHighContrast: …, darkHighContrast: …])` (high contrast: iOS's Increase Contrast setting).
 */
export function parseColorsSwift(src) {
  const tokens = {}
  for (const chunk of src.split(/\n\s*static let /).slice(1)) {
    const name = /^(dt_[a-z0-9_]+) = UIColor\(/.exec(chunk)?.[1]
    if (!name) throw new Error(`unexpected declaration: ${chunk.slice(0, 80)}`)
    const body = chunk.slice(chunk.indexOf('UIColor(') + 8)
    const single = /^hex8: (0x[0-9a-fA-F]{8})\)/.exec(body)
    if (single) {
      tokens[name] = { light: hex8(single[1]), dark: hex8(single[1]) }
      continue
    }
    const v = {}
    for (const [, key, val] of body.matchAll(/\b(light|dark|trueDark|elevatedDark|lightHighContrast|darkHighContrast): UIColor\(hex8: (0x[0-9a-fA-F]{8})\)/g)) v[key] = hex8(val)
    if (!v.light || !v.dark) throw new Error(`can't read ${name}: ${body}`)
    tokens[name] = v
  }
  return tokens
}

function harvestColors() {
  console.log('colors')
  const cached = DESIGN_TOKENS_DIR ? path.join(DESIGN_TOKENS_DIR, 'output/ios/Colors.swift') : ''
  const vendored = path.join(VENDOR_DIR, `design-tokens-${DESIGN_TOKENS_SHA}/Colors.swift`)
  const source = cached && fs.existsSync(cached) ? cached : need(vendored, `Colors.swift (design-tokens ${DESIGN_TOKENS_SHA})`)
  const src = fs.readFileSync(source, 'utf8')
  if (source === cached) {
    for (const f of ['output/ios/Colors.swift', 'output/ios/Presets.swift', 'scripts/ios-colors.ts']) {
      const to = path.join(VENDOR_DIR, `design-tokens-${DESIGN_TOKENS_SHA}`, path.basename(f))
      fs.mkdirSync(path.dirname(to), { recursive: true })
      fs.copyFileSync(path.join(DESIGN_TOKENS_DIR, f), to)
    }
  }
  const tokens = parseColorsSwift(src)
  const names = Object.keys(tokens)
  const header = `/* Generated by tools/ios/harvest.mjs from slack/design-tokens@${DESIGN_TOKENS_SHA} output/ios/Colors.swift. Do not edit. */\n`

  const block = (sel, pick) =>
    `${sel} {\n${names
      .map((n) => [n, pick(tokens[n])])
      .filter(([, v]) => v)
      .map(([n, v]) => `  --${n}: ${v};`)
      .join('\n')}\n}\n`
  const css =
    header +
    '/* Scoped to the simulated screen: [data-appearance] is set on .ios-screen (src/sim/Screen.tsx). */\n' +
    block(":root, [data-appearance='light']", (t) => t.light) +
    block("[data-appearance='dark']", (t) => t.dark) +
    '/* The only tokens with extra dark variants (design-tokens scripts/ios-colors.ts darkModeOverrides). */\n' +
    block("[data-appearance='dark'][data-dark-variant='true-dark']", (t) => t.trueDark) +
    block("[data-appearance='dark'][data-dark-variant='elevated']", (t) => t.elevatedDark) +
    '/* Increase Contrast (Settings › Accessibility › Display & Text Size): data-contrast="high" on .ios-screen. */\n' +
    block("[data-appearance='light'][data-contrast='high']", (t) => (t.lightHighContrast && t.lightHighContrast !== t.light ? t.lightHighContrast : undefined)) +
    block("[data-appearance='dark'][data-contrast='high']", (t) => (t.darkHighContrast && t.darkHighContrast !== t.dark ? t.darkHighContrast : undefined))
  write(path.join(ROOT, 'src/tokens/generated/colors.css'), css)

  const ts =
    `// Generated by tools/ios/harvest.mjs from slack/design-tokens@${DESIGN_TOKENS_SHA} output/ios/Colors.swift. Do not edit.\n` +
    `// Every iOS color token with its resolved values. Use tokens through \`color()\` (src/tokens/index.ts) so they follow\n` +
    `// light/dark; the raw values are for canvas, SVG exports and tests.\n\n` +
    `export interface ColorValue {\n  light: string\n  dark: string\n  trueDark?: string\n  elevatedDark?: string\n  lightHighContrast?: string\n  darkHighContrast?: string\n}\n\n` +
    `export const colorTokens = ${JSON.stringify(tokens, null, 2)} as const satisfies Record<string, ColorValue>\n\n` +
    `export type ColorToken = keyof typeof colorTokens\n`
  write(path.join(ROOT, 'src/tokens/generated/colors.ts'), ts)
  console.log(`  ${names.length} tokens from ${source.startsWith(ROOT) ? rel(source) : source}`)
}

// ------------------------------------------------------------------------------------------------- icons

const MONO = /^(#000000|#000|black)$/i

function harvestIcons() {
  console.log('icons')
  const dir = need(path.join(IOS_DIR, 'Modules/Data/Icon/ResourceBundle/Icons.xcassets'), 'Icons.xcassets')
  const manifest = fs.readFileSync(path.join(IOS_DIR, 'Modules/Data/Icon/Implementation/Generated/SKIconManifest.swift'), 'utf8')
  // SKIconManifest.svgHomeFilled → "home_filled.svg" (the `fileName` switch)
  const caseToFile = {}
  for (const [, c, f] of manifest.matchAll(/case \.(svg[A-Za-z0-9]+): return "([a-z0-9_]+)\.svg"/g)) caseToFile[c] = f

  const icons = {}
  for (const set of fs.readdirSync(dir).sort()) {
    if (!set.endsWith('.imageset')) continue
    const name = set.replace(/\.imageset$/, '')
    const file = path.join(dir, set, `${name}.svg`)
    if (!fs.existsSync(file)) continue
    const svg = fs.readFileSync(file, 'utf8')
    const open = /<svg([^>]*)>/.exec(svg)
    const vb = /viewBox="([^"]+)"/.exec(open[1])?.[1] ?? '0 0 20 20'
    let body = svg.slice(open.index + open[0].length, svg.lastIndexOf('</svg>')).trim()
    const paints = [...body.matchAll(/(?:fill|stroke)="([^"]+)"/g)].map((m) => m[1]).filter((p) => p !== 'none')
    const multicolor = paints.some((p) => !MONO.test(p))
    if (!multicolor) body = body.replace(/(fill|stroke)="(#000000|#000|black)"/gi, '$1="currentColor"')
    body = body.replace(/\s*\n\s*/g, '')
    icons[name] = multicolor ? { viewBox: vb, body, multicolor: true } : { viewBox: vb, body }
  }
  const byCase = Object.fromEntries(Object.entries(caseToFile).filter(([, f]) => icons[f]))
  write(path.join(ROOT, 'src/icons/generated/icons.json'), JSON.stringify(icons))
  write(path.join(ROOT, 'src/icons/generated/manifest.json'), JSON.stringify(byCase, null, 1))
  console.log(`  ${Object.keys(icons).length} icons (${Object.values(icons).filter((i) => i.multicolor).length} multicolor), ${Object.keys(byCase).length} SKIconManifest cases`)
}

// ------------------------------------------------------------------------------------------ fonts, sounds

function harvestFonts() {
  console.log('fonts')
  const dir = need(path.join(IOS_DIR, 'Modules/Data/Font/ResourceBundle/Font/Lato'), 'Lato fonts')
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.ttf')).sort()) {
    write(path.join(ROOT, 'public/fonts', f.replace(/\.ttf$/, '.woff')), ttfToWoff(fs.readFileSync(path.join(dir, f))))
  }
}

function harvestSounds() {
  console.log('sounds')
  const dir = need(path.join(IOS_DIR, 'App/Resource/Sounds'), 'App/Resource/Sounds')
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.mp3')).sort()) {
    const to = path.join(ROOT, 'public/sounds', f)
    fs.mkdirSync(path.dirname(to), { recursive: true })
    fs.copyFileSync(path.join(dir, f), to)
  }
  console.log(`  copied ${fs.readdirSync(path.join(ROOT, 'public/sounds')).length} sounds`)
}

if (want('colors')) harvestColors()
if (want('icons')) harvestIcons()
if (want('fonts')) harvestFonts()
if (want('sounds')) harvestSounds()
